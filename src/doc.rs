//! `coyote-apple doc <file.cy> [-o doc.md]` — generated API docs.
//!
//! Renders what the typechecker proved into markdown: invariants,
//! provenance, capabilities, programs (io/param/state surfaces), and
//! host fns with signatures. Docs that can't drift, because they're
//! generated from the checked artifact — not written by hand.

use coyote::ast::{IoDir, Qual};
use coyote::typeck::CTy;
use std::path::PathBuf;

fn dims(t: &CTy) -> String {
    format!("{:?}{:?}", t.dt, t.dims).to_lowercase()
}

fn qual(q: &Qual) -> &'static str {
    match q {
        Qual::Trainable => "trainable",
        Qual::Frozen => "frozen",
        Qual::Sealed => "sealed",
        Qual::Plain => "plain",
    }
}

pub fn run(args: &[String]) -> Result<(), i32> {
    let Some(file) = args.iter().find(|a| !a.starts_with('-')) else {
        eprintln!("usage: coyote-apple doc <file.cy> [-o doc.md]");
        return Err(2);
    };
    let out = args
        .windows(2)
        .find(|w| w[0] == "-o")
        .map(|w| PathBuf::from(&w[1]));
    let r = (|| -> Result<(), String> {
        let (_src, ast) =
            coyote::parser::parse_file(std::path::Path::new(file)).map_err(|d| d.to_string())?;
        let c = coyote::typeck::check_all(&ast).map_err(|d| d.to_string())?;
        let mut md = String::new();
        md.push_str(&format!("# `{file}`\n\n"));
        md.push_str(
            "_generated by `coyote-apple doc` — reflects the checked program, not the comments_\n\n",
        );

        if !c.invariants.is_empty() {
            md.push_str("## invariants\n\n");
            for i in &c.invariants {
                md.push_str(&format!("- `{i}`\n"));
            }
            md.push('\n');
        }
        if !c.caps.is_empty() {
            md.push_str(&format!(
                "**capabilities:** {}\n\n",
                c.caps
                    .iter()
                    .map(|s| format!("`{s}`"))
                    .collect::<Vec<_>>()
                    .join(" ")
            ));
        }
        for (name, p) in &c.ane {
            md.push_str(&format!("## program `{name}`\n\n"));
            if !p.ios.is_empty() {
                md.push_str("| port | dir | type |\n|---|---|---|\n");
                for (pn, d, t) in &p.ios {
                    let dir = match d {
                        IoDir::In => "in",
                        IoDir::Out => "out",
                    };
                    md.push_str(&format!("| `{pn}` | {dir} | `{}` |\n", dims(t)));
                }
                md.push('\n');
            }
            if !p.params.is_empty() {
                md.push_str("| param | qual | type | src |\n|---|---|---|---|\n");
                for pr in &p.params {
                    let src = pr.src.as_deref().unwrap_or("—");
                    md.push_str(&format!(
                        "| `{}` | {} | `{}` | `{src}` |\n",
                        pr.name,
                        qual(&pr.qual),
                        dims(&pr.ty)
                    ));
                }
                md.push('\n');
            }
            if !p.states.is_empty() {
                md.push_str("| state | port | type |\n|---|---|---|\n");
                for (k, port, t) in &p.states {
                    md.push_str(&format!("| `{k}` | `{port}` | `{}` |\n", dims(t)));
                }
                md.push('\n');
            }
            md.push_str(&format!(
                "body: {} stmts → `{}`\n\n",
                p.body.len(),
                dims(&p.ret.ty)
            ));
            if !p.provenance.is_empty() {
                for (k, v) in &p.provenance {
                    md.push_str(&format!("- **{k}** {v}\n"));
                }
                md.push('\n');
            }
        }
        if let Some(h) = &c.host {
            md.push_str("## host\n\n| fn | signature |\n|---|---|\n");
            for f in &h.fns {
                let arg_s = f
                    .args
                    .iter()
                    .map(|(n, t)| format!("{n}: {}", t.show(&h.structs, &h.enums)))
                    .collect::<Vec<_>>()
                    .join(", ");
                let tag = if f.is_reflex { " ·reflex" } else { "" };
                md.push_str(&format!(
                    "| `{}{tag}` | `({arg_s}) -> {}` |\n",
                    f.name,
                    f.ret.show(&h.structs, &h.enums)
                ));
            }
            md.push('\n');
        }
        if let Some(o) = out {
            std::fs::write(&o, &md).map_err(|e| format!("{}: {e}", o.display()))?;
            println!("✓ doc → {}", o.display());
        } else {
            print!("{md}");
        }
        Ok(())
    })();
    r.map_err(|e| {
        eprintln!("✗ {e}");
        1
    })
}
