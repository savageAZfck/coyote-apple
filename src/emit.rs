//! `coyote-apple emit <file.cy> --swift [-o File.swift] [--class Name]`
//!
//! The adoption surface: generate a typed Swift wrapper for a `.cy`
//! organism, bound to libcoyote's C ABI. A Swift app runs an organism
//! in three lines:
//!
//!   let org = ProbeOrganism(path: "main.cy", outDir: "out", useCpu: true)
//!   org?.main()
//!   print(org?.witnessCount ?? 0)
//!
//! Generated methods come from the *checked* file — i64 host fns map
//! to `Int64` Swift calls, single-str fns (reflexes, string organs)
//! map through the string ABI. Non-bridgeable signatures are emitted
//! as comments, not silently dropped.

use coyote::hostck::{HProgram, RTy};
use std::path::PathBuf;

fn is_i64_callable(f: &coyote::hostck::HFnT) -> bool {
    f.args.iter().all(|(_, t)| matches!(t, RTy::I64)) && matches!(f.ret, RTy::I64 | RTy::Unit)
}

fn is_str_callable(f: &coyote::hostck::HFnT) -> bool {
    f.args.len() == 1 && matches!(f.args[0].1, RTy::Str)
}

fn swift_for(file: &str, class: &str, h: &HProgram) -> String {
    let mut s = String::new();
    s.push_str(&format!(
        "// {class}.swift — generated by `coyote-apple emit {file} --swift`.\n\
         // Do not edit; regenerate from the .cy source.\n//\n\
         // Link: swiftc app.swift {class}.swift -L<dir> -lcoyote\n\
         // Run:  DYLD_LIBRARY_PATH=<dir> ./app\n\n\
         import Foundation\n\n"
    ));
    // ---- raw ABI bindings ----
    s.push_str("// MARK: - libcoyote ABI\n\n");
    for (name, sig) in [
        ("coyote_last_error", "() -> UnsafePointer<CChar>?"),
        (
            "coyote_open",
            "(_ : UnsafePointer<CChar>?, _ : UnsafePointer<CChar>?, _ : Bool) -> OpaquePointer?",
        ),
        ("coyote_close", "(_ : OpaquePointer?) -> Void"),
        (
            "coyote_run_main_i64",
            "(_ : OpaquePointer?, _ : UnsafeMutablePointer<Int64>?) -> Bool",
        ),
        (
            "coyote_call_i64",
            "(_ : OpaquePointer?, _ : UnsafePointer<CChar>?, _ : UnsafePointer<Int64>?, _ : Int, _ : UnsafeMutablePointer<Int64>?) -> Bool",
        ),
        (
            "coyote_call_str",
            "(_ : OpaquePointer?, _ : UnsafePointer<CChar>?, _ : UnsafePointer<CChar>?, _ : UnsafeMutablePointer<CChar>?, _ : Int) -> Int",
        ),
        ("coyote_witness_count", "(_ : OpaquePointer?) -> Int"),
        (
            "coyote_witness_json",
            "(_ : OpaquePointer?, _ : UnsafeMutablePointer<CChar>?, _ : Int) -> Int",
        ),
    ] {
        s.push_str(&format!(
            "@_silgen_name(\"{name}\")\nprivate func _{name}{sig}\n"
        ));
    }
    // ---- error type ----
    s.push_str(
        "\n// MARK: - wrapper\n\npublic enum CoyoteError: Error, CustomStringConvertible {\n    case openFailed(String)\n    case callFailed(String)\n    public var description: String {\n        switch self {\n        case .openFailed(let m): return \"coyote_open: \\(m)\"\n        case .callFailed(let m): return \"coyote_call: \\(m)\"\n        }\n    }\n}\n\n",
    );
    s.push_str(&format!(
        "public final class {class} {{\n    private var vm: OpaquePointer?\n\n    /// compile + load the organism (emit cache → compile → resident VM)\n    public init?(path: String, outDir: String = \"out\", useCpu: Bool = false) {{\n        vm = path.withCString {{ p in\n            outDir.withCString {{ d in _coyote_open(p, d, useCpu) }}\n        }}\n    }}\n\n    deinit {{ if let v = vm {{ _coyote_close(v) }} }}\n\n    public static var lastError: String {{\n        guard let p = _coyote_last_error() else {{ return \"unknown error\" }}\n        return String(cString: p)\n    }}\n\n"
    ));
    // ---- main entry ----
    s.push_str(
        "    /// run `host fn main()` — the organism's observable behavior\n    @discardableResult\n    public func main() -> Int64 {\n        var out: Int64 = 0\n        guard let v = vm else { return 0 }\n        _ = _coyote_run_main_i64(v, &out)\n        return out\n    }\n\n",
    );
    // ---- per-fn bridges ----
    s.push_str("    // MARK: organism fns\n\n");
    for f in &h.fns {
        if f.name == "main" || f.name.starts_with("test_") {
            continue;
        }
        if is_i64_callable(f) {
            let params = f
                .args
                .iter()
                .map(|(n, _)| format!("_ {n}: Int64"))
                .collect::<Vec<_>>()
                .join(", ");
            let arr = f
                .args
                .iter()
                .map(|(n, _)| n.clone())
                .collect::<Vec<_>>()
                .join(", ");
            s.push_str(&format!(
                "    public func {}({}) -> Int64 {{\n        var out: Int64 = 0\n        guard let v = vm else {{ return 0 }}\n        var args: [Int64] = [{}]\n        args.withUnsafeBufferPointer {{ bp in\n            _ = \"{}\".withCString {{ n in _coyote_call_i64(v, n, bp.baseAddress, bp.count, &out) }}\n        }}\n        return out\n    }}\n\n",
                f.name, params, arr, f.name
            ));
        } else if is_str_callable(f) {
            let an = &f.args[0].0;
            s.push_str(&format!(
                "    public func {}(_ {}: String) -> String {{\n        guard let v = vm else {{ return \"\" }}\n        var buf = [CChar](repeating: 0, count: 8192)\n        let n = \"{}\".withCString {{ fname in\n            {}.withCString {{ a in\n                _coyote_call_str(v, fname, a, &buf, buf.count)\n            }}\n        }}\n        guard n > 0 else {{ return \"\" }}\n        return String(cString: buf)\n    }}\n\n",
                f.name, an, f.name, an
            ));
        } else {
            let sig = f
                .args
                .iter()
                .map(|(n, _)| n.as_str())
                .collect::<Vec<_>>()
                .join(", ");
            s.push_str(&format!(
                "    // `{}` ({sig}) — not bridgeable via the current ABI\n    //   (i64 arg lists and single-str calls are bridged; widen the ABI for the rest)\n\n",
                f.name
            ));
        }
    }
    // ---- witness ----
    s.push_str(
        "    // MARK: witness\n\n    /// hash-chained entries the organism logged\n    public var witnessCount: Int {\n        guard let v = vm else { return 0 }\n        return _coyote_witness_count(v)\n    }\n\n    /// the full chain as JSONL\n    public func witnessJSON() -> String {\n        guard let v = vm else { return \"\" }\n        var buf = [CChar](repeating: 0, count: 65536)\n        let n = _coyote_witness_json(v, &buf, buf.count)\n        guard n > 0 else { return \"\" }\n        return String(cString: buf)\n    }\n}\n",
    );
    s
}

pub fn run(args: &[String]) -> Result<(), i32> {
    let Some(file) = args.iter().find(|a| !a.starts_with('-')) else {
        eprintln!("usage: coyote-apple emit <file.cy> --swift [-o File.swift] [--class Name]");
        return Err(2);
    };
    if !args.iter().any(|a| a == "--swift") {
        eprintln!("usage: coyote-apple emit <file.cy> --swift [-o File.swift] [--class Name]");
        return Err(2);
    }
    let r = (|| -> Result<(), String> {
        let path = std::path::Path::new(file);
        let (_src, ast) = coyote::parser::parse_file(path).map_err(|d| d.to_string())?;
        let c = coyote::typeck::check_all(&ast).map_err(|d| d.to_string())?;
        let Some(h) = c.host.as_ref() else {
            return Err(format!(
                "{file}: no host stratum — Swift bridge wraps organisms (`host fn`s), not bare programs"
            ));
        };
        let stem = path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or("organism");
        let class = args
            .windows(2)
            .find(|w| w[0] == "--class")
            .map(|w| w[1].clone())
            .unwrap_or_else(|| {
                let mut ch = stem.chars();
                match ch.next() {
                    Some(f) => f.to_uppercase().collect::<String>() + ch.as_str(),
                    None => "Organism".into(),
                }
            });
        let src = swift_for(file, &class, h);
        let out = args
            .windows(2)
            .find(|w| w[0] == "-o")
            .map(|w| PathBuf::from(&w[1]))
            .unwrap_or_else(|| PathBuf::from(format!("{class}.swift")));
        std::fs::write(&out, &src).map_err(|e| format!("{}: {e}", out.display()))?;
        let n_i64 = h.fns.iter().filter(|f| is_i64_callable(f)).count();
        let n_str = h.fns.iter().filter(|f| is_str_callable(f)).count();
        println!(
            "✓ {} → {} — main + {} i64 fns, {} str fns, witness accessors",
            file,
            out.display(),
            n_i64,
            n_str
        );
        Ok(())
    })();
    r.map_err(|e| {
        eprintln!("✗ {e}");
        1
    })
}
